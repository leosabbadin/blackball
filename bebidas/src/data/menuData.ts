/**
 * Normaliza textos removendo acentuação, caracteres especiais, cedilha, pontuações e espaços extras
 */
export const normalizeText = (text: string = ''): string =>
  text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/['’"`´\-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

/**
 * Função de busca inteligente que pesquisa em múltiplos campos (nome, categoria, marca, descrição, opções, keywords)
 */
export const matchesSearch = (dish: Dish, rawQuery: string): boolean => {
  if (!rawQuery.trim()) return true;
  const q = normalizeText(rawQuery);
  const words = q.split(/\s+/).filter(Boolean);

  const searchableFields = [
    dish.name,
    dish.category,
    dish.categoryName || '',
    dish.description || '',
    dish.fullDescription || '',
    dish.quantity || '',
    dish.observation || '',
    ...(dish.options || []),
    ...(dish.keywords || []),
    ...(dish.ingredients || []),
  ].map(normalizeText);

  const combined = searchableFields.join(' ');

  // Todas as palavras digitadas devem ser encontradas nos campos pesquisáveis
  return words.every((word) => combined.includes(word));
};

