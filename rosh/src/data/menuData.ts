/**
 * Funções auxiliares de busca e filtragem com remoção de acentuação
 */
export const normalizeText = (text: string): string => {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
};

export const matchesSearch = (dish: Dish, query: string): boolean => {
  if (!query.trim()) return true;
  const q = normalizeText(query.trim());

  if (normalizeText(dish.name).includes(q)) return true;
  if (dish.flavor && normalizeText(dish.flavor).includes(q)) return true;
  if (dish.description && normalizeText(dish.description).includes(q)) return true;
  if (dish.fullDescription && normalizeText(dish.fullDescription).includes(q)) return true;
  if (dish.categoryName && normalizeText(dish.categoryName).includes(q)) return true;
  if (dish.category && normalizeText(dish.category).includes(q)) return true;
  if (dish.keywords && dish.keywords.some((k) => normalizeText(k).includes(q))) return true;

  return false;
};
